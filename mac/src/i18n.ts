export function t(key: string): string { return dict[lang][key] ?? dict.en[key] ?? key; }

/** Gateway errors arrive as dictionary keys; anything else is shown as is. */
export function errorText(error: string | null): string { return error ? (dict[lang][error] ?? dict.en[error] ?? error) : ''; }
